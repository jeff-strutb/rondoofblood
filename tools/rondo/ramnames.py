#!/usr/bin/env python3
"""ramnames.py -- write the RAM and hardware names from config/rondo/symbols.csv.

The one list of names, written as a C header and an assembler include so the
two decompilations cannot name a byte differently.

    python3 tools/rondo/ramnames.py
"""
import os

TOP = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CSV = os.path.join(TOP, "config", "rondo", "symbols.csv")


def load():
    """Every row of the list: (address, kind, name, note)."""
    rows = []
    with open(CSV, encoding="ascii") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or line.startswith("addr,"):
                continue
            addr, kind, name, note = line.split(",", 3)
            rows.append((int(addr, 16), kind, name, note))
    return rows


def main():
    rows = load()
    head = "generated by tools/rondo/ramnames.py from config/rondo/symbols.csv"
    h = [f"/* {head} */", "#ifndef RONDO_RAM_H", "#define RONDO_RAM_H", ""]
    s = [f"; {head}"]
    for addr, kind, name, note in rows:
        full = addr + 0x2000 if kind == "zp" else addr
        h.append(f"#define {name} 0x{full:04X} /* {note} */")
        width = 2 if kind == "zp" else 4
        s.append(f"{name} = ${addr:0{width}X} ; {note}")
    h += ["", "#endif", ""]
    for path, lines in ((os.path.join(TOP, "src", "rondo", "include", "ram.h"), h),
                        (os.path.join(TOP, "asm", "rondo", "include", "ram.inc"), s)):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="ascii", newline="\n") as f:
            f.write("\n".join(lines) + ("\n" if lines[-1] else ""))
    print(f"{len(rows)} names")


if __name__ == "__main__":
    main()
